import '../../domain/entities/endereco_entity.dart';
import '../mappers/database_enums.dart';

class EnderecoModel extends EnderecoEntity {
  const EnderecoModel({
    required super.id,
    required super.usuarioId,
    required super.tipo,
    required super.logradouro,
    super.numero,
    super.complemento,
    super.bairro,
    required super.cidade,
    required super.estado,
    super.cep,
    super.latitude,
    super.longitude,
    required super.criadoEm,
  });
  factory EnderecoModel.fromJson(Map<String, dynamic> j) => EnderecoModel(
    id: j['id'],
    usuarioId: j['usuario_id'],
    tipo: TipoEnderecoMapper.fromDatabase(j['tipo']),
    logradouro: j['logradouro'],
    numero: j['numero'],
    complemento: j['complemento'],
    bairro: j['bairro'],
    cidade: j['cidade'],
    estado: j['estado'],
    cep: j['cep'],
    latitude: (j['latitude'] as num?)?.toDouble(),
    longitude: (j['longitude'] as num?)?.toDouble(),
    criadoEm: DateTime.parse(j['criado_em']),
  );
  Map<String, dynamic> toJson() => {
    'id': id,
    'usuario_id': usuarioId,
    'tipo': tipo.databaseValue,
    'logradouro': logradouro,
    'numero': numero,
    'complemento': complemento,
    'bairro': bairro,
    'cidade': cidade,
    'estado': estado,
    'cep': cep,
    'latitude': latitude,
    'longitude': longitude,
    'criado_em': criadoEm.toIso8601String(),
  };
  EnderecoEntity toEntity() => EnderecoEntity(
    id: id,
    usuarioId: usuarioId,
    tipo: tipo,
    logradouro: logradouro,
    numero: numero,
    complemento: complemento,
    bairro: bairro,
    cidade: cidade,
    estado: estado,
    cep: cep,
    latitude: latitude,
    longitude: longitude,
    criadoEm: criadoEm,
  );
  factory EnderecoModel.fromEntity(EnderecoEntity e) => EnderecoModel(
    id: e.id,
    usuarioId: e.usuarioId,
    tipo: e.tipo,
    logradouro: e.logradouro,
    numero: e.numero,
    complemento: e.complemento,
    bairro: e.bairro,
    cidade: e.cidade,
    estado: e.estado,
    cep: e.cep,
    latitude: e.latitude,
    longitude: e.longitude,
    criadoEm: e.criadoEm,
  );
}
